                          '<p><strong class="side-heading">What it is in general:</strong>\n'
                          'The exact dividing line between customer and cloud provider shifts based on the chosen '
                          'cloud service model. In <strong class="keyword">IaaS</strong>, the customer manages the '
                          'entire software stack above the hypervisor: operating system selection, kernel updates, '
                          'system libraries, middleware, application binaries, and firewall ports. In <strong '
                          'class="keyword">PaaS / CaaS</strong>, the cloud provider manages host server operating '
                          'systems, container orchestration engines, and physical clustering; the customer is '
                          'responsible for the container image layers, application source code, configuration '
                          'variables, and API authentication. In <strong class="keyword">SaaS</strong>, the provider '
                          'manages the entire application, database, and infrastructure; the customer is responsible '
                          'only for user authorization, data input, and access policy governance.</p>\n'
                          '\n'
                          '<p><strong class="side-heading">Relevance to a cloud architect:</strong>\n'
                          'Understanding these shifting boundaries allows an architect to minimize operational risk '
                          'and maintenance overhead. For instance, selecting Compute Engine (IaaS) for an enterprise '
                          'application requires budgeting engineering resources for periodic kernel CVE remediation, '
                          'automated OS patch management schedules, and vulnerability scanning on virtual machine disk '
                          'images. In contrast, selecting Cloud Run (PaaS) shifts host kernel vulnerability mitigation '
                          "entirely to Google SREs, reducing the customer's security surface to application container "
                          'dependencies and IAM invoker controls.</p>\n'
                          '\n'
                          '<p><strong class="side-heading">Relevance to GCP:</strong>\n'
                          'In Compute Engine, Google provides the <strong class="keyword">VM Manager</strong> suite '
                          '(comprising OS Config, OS Patch management, and OS Inventory management) to help customers '
                          'fulfill their OS patching duty, but Google does not execute patches automatically without '
                          'customer policy configuration. In GKE Standard, the customer must manage node pool upgrade '
                          'schedules, whereas in GKE Autopilot, Google automatically upgrades node operating systems '
                          'and worker Kubernetes versions. In Cloud Run, Google manages 100% of the underlying '
                          'container execution host, guaranteeing that host kernel vulnerabilities (e.g., Dirty Pipe '
                          'or Spectre/Meltdown mitigations) are patched without customer intervention.</p>\n'
