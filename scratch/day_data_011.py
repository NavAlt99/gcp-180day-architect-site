                          '<h3>Identity, Access Management (IAM), and Ingress Protection as Customer Invariants</h3>\n'
                          '\n'
                          '<p><strong class="side-heading">What it is in general:</strong>\n'
                          'Regardless of whether an architect deploys IaaS, PaaS, FaaS, or SaaS, <strong '
                          'class="keyword">Identity and Access Management (IAM)</strong>, authentication, and network '
                          'ingress controls remain strict customer invariants. The cloud provider cannot know which '
                          'employees should access a payroll database, which third-party APIs require webhook access, '
                          'or which external IP addresses represent legitimate traffic versus attackers. Defining who '
                          'can invoke an API, what roles are assigned to service accounts, and how network perimeter '
                          'firewalls filter traffic is always a tenant responsibility.</p>\n'
                          '\n'
                          '<p><strong class="side-heading">Relevance to a cloud architect:</strong>\n'
                          'A failure in IAM or network ingress instantly invalidates all underlying infrastructure '
                          'security controls. If an architect grants <kbd>roles/run.invoker</kbd> or '
                          '<kbd>roles/storage.objectViewer</kbd> to <kbd>allUsers</kbd>, unauthenticated internet '
                          'clients can query private APIs or exfiltrate sensitive data, regardless of how secure '
                          "Google's physical data centers or hypervisors are. Architects must strictly enforce the "
                          'principle of least privilege, disable automatic default service account editor permissions, '
                          'mandate multi-factor authentication (<strong class="keyword">MFA</strong>), and deploy Web '
                          'Application Firewalls (<strong class="keyword">WAF</strong>) to inspect application-layer '
                          'requests.</p>\n'
                          '\n'
                          '<p><strong class="side-heading">Relevance to GCP:</strong>\n'
                          'In Google Cloud, customer access governance is enforced via <strong class="keyword">Cloud '
                          'IAM</strong>, utilizing fine-grained roles and condition-based bindings (such as '
                          'restricting access by client IP or date/time). Service-to-service communication is secured '
